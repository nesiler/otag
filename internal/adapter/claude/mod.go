// The mod is a Claude Code plugin loaded with --plugin-dir for this run only. Its
// turn.complete hook reports the end of every main-agent turn through
// `otag event claude mod-turn-complete --run <run>`: settings hooks see no Stop when the
// user presses Esc or refuses a permission, so this is the one reliable turn-end signal.
// It also delivers messages to an idle session: it polls RunDir/inbox (see deliver.go)
// and submits each message as a user turn ($.prompt.submit).

// ModTurnComplete is the hook kind the mod reports.
const ModTurnComplete = "mod-turn-complete"

const pluginJSON = `{
  "name": "otag",
  "version": "0.3.0",
  "description": "otag: reports turn ends of this session to otag and submits its messages"
}
`

const modHooksJSON = `{ "modules": ["./register.ts"] }
`

// modMaxAge: the mod skips inbox messages older than this. It stays below the
// mod_submit proof timeout (3 min, daemon.ProofTimeouts): a message the mod submits
// is always one whose attempt can still be proven, never one already settled unknown
// (otag never re-sends those on its own).
const modMaxAge = 2 * time.Minute

// registerTS is the hooks module. $ may only be passed to top-level functions
// (validator rule), hence report(). It must never throw into Claude Code: a failing
// otag only loses an event.
const registerTS = `import type { Register } from 'claude-code'

// Generated by otag for run %RUN%; do not edit.
const OTAG: string = %OTAG%
const RUN: string = %RUNJS%
const ENV: Record<string, string> = %ENV%
const INBOX: string = %INBOX%
const MAX_AGE_MS = %MAXAGE%

let taking = false
let polling = false

async function report($: any, kind: string, payload: unknown) {
  try {
    await $.process.run([OTAG, 'event', 'claude', kind, '--run', RUN], {
      stdin: JSON.stringify(payload),
      env: ENV,
    })
  } catch {
    // otag unavailable: the turn end is lost, the session goes on
  }
}

// takeInbox submits the messages otag left in the inbox, oldest first. A file is
// emptied before its text is submitted, so it is never submitted twice; otag removes
// the empty files.
async function takeInbox($: any) {
  if (taking) return
  taking = true
  try {
    const entries = await $.fs.list(INBOX)
    const files = entries
      .filter((f: any) => f.kind === 'file' && f.size > 0 && f.name.endsWith('.json'))
      .sort((a: any, b: any) => a.mtimeMs - b.mtimeMs)
    for (const f of files) {
      const path = INBOX + '/' + f.name
      let item: any
      try {
        item = JSON.parse(await $.fs.read(path))
      } catch {
        item = undefined
      }
      await $.fs.write(path, '')
      if (!item || typeof item.text !== 'string' || item.text === '') continue
      if (typeof item.at === 'number' && Date.now() - item.at > MAX_AGE_MS) continue
      void $.prompt.submit({ text: item.text })
    }
  } catch {
    // no inbox, or it is unreadable: try again on the next tick
  } finally {
    taking = false
  }
}

async function markReady($: any) {
  try {
    await $.fs.write(INBOX + '/.mod-ready', String(Date.now()))
  } catch {
    // without the ready file otag does not deliver here while idle
  }
}

export const register: Register = on => {
  on('session.start', async ($, e, next) => {
    await markReady($)
    if (!polling) {
      polling = true
      $.clock.every(1000, () => {
        // The ready file's mtime is the mod's heartbeat: otag writes no inbox file
        // when it is stale.
        void markReady($)
        void takeInbox($)
      })
    }
    return next(e)
  })

  on('turn.complete', async ($, e, next) => {
    const t = e as any
    const answer = typeof t.answer === 'string' ? t.answer.slice(0, 2000) : undefined
    await report($, 'mod-turn-complete', {
      run: RUN,
      turnId: t.turnId,
      agentId: t.agentId,
      isAborted: t.isAborted,
      reason: t.reason,
      durationMs: t.durationMs,
      answer,
    })
    return next(e)
  })
}
`

// modFiles returns the plugin directory's files (paths relative to RunDir).
func modFiles(spec adapter.RunSpec) ([]adapter.File, error) {
	js := func(v any) (string, error) {
		b, err := json.Marshal(v)
		return string(b), err
	}
	otag, err := js(spec.OtagBin)
	if err != nil {
		return nil, err
	}
	run, err := js(spec.RunID)
	if err != nil {
		return nil, err
	}
	inbox, err := js(filepath.Join(spec.RunDir, inboxDir))
	if err != nil {
		return nil, err
	}
	// The env otag puts on the pane (OTAG_DB, OTAG_DATA_DIR, ...), so `otag event` finds the
	// same database whether or not $.process.run inherits the session's environment.
	keys := make([]string, 0, len(spec.Env))
	for k := range spec.Env {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	var env strings.Builder
	env.WriteString("{")
	for i, k := range keys {
		kj, _ := js(k)
		vj, _ := js(spec.Env[k])
		if i > 0 {
			env.WriteString(", ")
		}
		env.WriteString(kj + ": " + vj)
	}
	env.WriteString("}")
	src := strings.NewReplacer(
		"%RUN%", strings.NewReplacer("\n", " ", "\r", " ").Replace(spec.RunID),
		"%OTAG%", otag, "%RUNJS%", run, "%ENV%", env.String(), "%INBOX%", inbox,
		"%MAXAGE%", strconv.FormatInt(modMaxAge.Milliseconds(), 10),
	).Replace(registerTS)
	return []adapter.File{
		{Path: path.Join(modDir, ".claude-plugin", "plugin.json"), Data: []byte(pluginJSON)},
		{Path: path.Join(modDir, "hooks", "hooks.json"), Data: []byte(modHooksJSON)},
		{Path: path.Join(modDir, "hooks", "register.ts"), Data: []byte(src)},
	}, nil
}
